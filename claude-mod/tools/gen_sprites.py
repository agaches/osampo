"""Turns the board's sprite sheets into hooks/sprites.gen.ts for the Claude Code mod.

Each 64 x 64 pose is kept at full size and the 240 x 284 backgrounds are cut to the
board's pixel (80 x 96), so a full scene is 80 terminal columns by 48 rows of half
blocks; hooks/scene.ts halves it for a narrow panel. Frames are run-length coded.
Run: python3 -I claude-mod/tools/gen_sprites.py (needs Pillow).
"""

import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SPRITES = os.path.join(ROOT, 'widgets', 'osampo', 'ui', 'sprites')
OUT = os.path.join(ROOT, 'claude-mod', 'hooks', 'sprites.gen.ts')

SHEETS = ['repos', 'boude', 'patte', 'aboie', 'laisse', 'dort', 'niche', 'content', 'roulade',
          'court', 'balle', 'lache', 'os', 'os_fin', 'bain', 'bain_mousse', 'bain_fin',
          'promenade', 'tournis']
DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'


def encode(im):
    """Palette of 0xAARRGGBB ints and one index character per pixel, row-major."""
    palette, chars = [], []
    for p in im.getdata():
        p = (0, 0, 0, 0) if p[3] == 0 else p
        argb = (p[3] << 24) | (p[0] << 16) | (p[1] << 8) | p[2]
        if argb not in palette:
            palette.append(argb)
        chars.append(DIGITS[palette.index(argb)])
    assert len(palette) <= len(DIGITS), len(palette)
    return palette, ''.join(chars)


def rle(chars):
    """Runs of 4 or more: '~', the character, the length in two base-36 digits."""
    out, i = [], 0
    while i < len(chars):
        j = i
        while j < len(chars) and chars[j] == chars[i] and j - i < 36 * 36 - 1:
            j += 1
        n = j - i
        out.append(f'~{chars[i]}{DIGITS[n // 36]}{DIGITS[n % 36]}' if n >= 4 else chars[i] * n)
        i = j
    return ''.join(out)


def sheet(name):
    img = Image.open(os.path.join(SPRITES, name + '.png')).convert('RGBA')
    palette, chars = encode(img)
    rows = [chars[r * img.width:(r + 1) * img.width] for r in range(64)]
    per = [rle(''.join(row[64 * i:64 * i + 64] for row in rows)) for i in range(img.width // 64)]
    return {'p': palette, 'f': per}


def background(name):
    bg = Image.open(os.path.join(SPRITES, name + '.png')).convert('RGBA').resize((80, 95), Image.NEAREST)
    full = Image.new('RGBA', (80, 96))
    full.paste(bg, (0, 0))
    full.paste(bg.crop((0, 94, 80, 95)), (0, 95))
    palette, chars = encode(full)
    return {'p': palette, 'f': [rle(chars)]}


def main():
    data = {name: sheet(name) for name in SHEETS}
    data['fond_jour'] = background('fond_jour')
    data['fond_nuit'] = background('fond_nuit')
    lines = [
        '// Generated by claude-mod/tools/gen_sprites.py from widgets/osampo/ui/sprites. Do not edit.',
        '// Front-facing puppy poses: derived from the puppy of strawheart (Animals and Tea,',
        '// http://mtsids.com/, https://opengameart.org/content/animals-and-tea-by-strawheart),',
        '// under CC-BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/). Credits: ../ASSETS.md.',
        '',
        'export type Sheet = { p: readonly number[]; f: readonly string[] }',
        '',
        'export const SHEETS = {',
    ]
    for name, s in data.items():
        lines.append(f'  {name}: {json.dumps(s, separators=(",", ":"))},')
    lines += ['} as const satisfies Record<string, Sheet>', '', 'export type SheetName = keyof typeof SHEETS', '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    frames = sum(len(s['f']) for s in data.values())
    print(f'{OUT}: {len(data)} sheets, {frames} frames, {os.path.getsize(OUT) // 1024} KiB')


if __name__ == '__main__':
    sys.exit(main())
